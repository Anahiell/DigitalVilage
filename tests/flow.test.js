import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
const sleep=t=>new Promise(r=>setTimeout(r,t));
test('complete simulation: private accounts, roles, dynamic economy and five rounds',async t=>{
 const tmp=await mkdtemp(join(tmpdir(),'digital-village-'));
 const port=31000+Math.floor(Math.random()*20000),base=`http://127.0.0.1:${port}`;
 const adminPass='integration-admin-password-very-long',pepper='integration-pepper-at-least-twenty-characters';
 const env={...process.env,HOST:'127.0.0.1',PORT:String(port),ADMIN_PASSWORD:adminPass,PIN_PEPPER:pepper,DB_PATH:join(tmp,'world.db'),DEV_EMAIL_OUTBOX:'1',SMTP_EMAIL:'',SMTP_APP_PASSWORD:'',RESEND_API_KEY:'',EMAIL_FROM:'',EXERCISE_SMTP_EMAIL:'',EXERCISE_SMTP_APP_PASSWORD:'',PUBLIC_BASE_URL:base,NODE_ENV:'development'};
 const child=spawn(process.execPath,['server.js'],{cwd:process.cwd(),env,stdio:['ignore','pipe','pipe']});
 let errs='';child.stderr.on('data',d=>errs+=d);
 t.after(async()=>{child.kill();await sleep(200);await rm(tmp,{recursive:true,force:true});});
 async function request(path,body,cookie){const res=await fetch(base+'/api/'+path,{method:body===undefined?'GET':'POST',headers:{...(body===undefined?{}:{'content-type':'application/json'}),...(cookie?{Cookie:cookie}:{})},body:body===undefined?undefined:JSON.stringify(body)});const json=await res.json();return {status:res.status,json,cookie:res.headers.get('set-cookie')?.split(';')[0]};}
 let up=false;for(let n=0;n<100;n++){if(child.exitCode!==null)throw Error('server crashed: '+errs);try{const r=await request('state');if(r.status===200){up=true;break;}}catch{}await sleep(90);}assert.ok(up,errs);
 const initial=(await request('state')).json;
 assert.equal(initial.villages.length,4);assert.equal(initial.game.round,0);
 assert.equal((await request('register',{name:'Alice Mayor',email:'alice@test.example',village:'green-valley',role:'mayor',consentEmail:true})).status,200);
 assert.equal((await request('register',{name:'Bob Mayor',email:'bob@test.example',village:'green-valley',role:'mayor'})).status,409);
 const a=await request('admin/login',{password:adminPass});assert.equal(a.status,200);const admin=a.cookie;
 let s=(await request('state',undefined,admin)).json;assert.equal(s.admin,true);assert.equal(s.stats.registered,1);
 const mail=s.outbox.find(m=>m.email==='alice@test.example');assert.ok(mail);
 const pin=mail.body.match(/PIN is: (\d{6})/)[1];assert.ok(pin);
 const bad=await request('login',{email:'alice@test.example',pin:'12345'});assert.equal(bad.status,401);
 const l=await request('login',{email:'alice@test.example',pin});assert.equal(l.status,200);const alice=l.cookie;
 s=(await request('state',undefined,alice)).json;assert.equal(s.me.role,'mayor');assert.equal(s.admin,undefined);
 assert.equal((await request('action',{op:'grant',village:'green-valley',amount:100000},alice)).status,403);
 assert.equal((await request('action',{op:'start'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.round,1);
 assert.equal((await request('action',{op:'invest',id:'fiber'},alice)).status,200);
 assert.equal((await request('action',{op:'invest',id:'fiber'},alice)).status,409);
 s=(await request('state',undefined,alice)).json;assert.equal(s.villages[0].budget,79000);assert.equal(s.villages[0].internet,67);
 const db=new DatabaseSync(join(tmp,'world.db'));
 db.exec(`UPDATE game SET last_sim_at=last_sim_at-40000 WHERE id=1`);
 s=(await request('state',undefined,alice)).json;assert.ok(s.histories['green-valley'].length>=3);assert.notEqual(s.villages[0].budget,79000);
 assert.equal((await request('action',{op:'grant',amount:10000,village:'green-valley'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.ok(s.villages[0].budget>88000);
 assert.equal((await request('action',{op:'shock'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.crisisFired,true);assert.ok(s.villages[0].budget<70000);
 db.exec('UPDATE game SET last_dynamic_event_at=last_dynamic_event_at-130000 WHERE id=1');
 s=(await request('state',undefined,alice)).json;assert.ok(s.events.some(e=>e.kind==='random'));
 const randomCount=s.events.filter(e=>e.kind==='random').length;
 s=(await request('state',undefined,alice)).json;assert.equal(s.events.filter(e=>e.kind==='random').length,randomCount);
 assert.equal((await request('action',{op:'next'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.round,2);assert.equal(s.news.length,28);assert.ok(!('authentic' in s.news[0]));
 const generated=(await request('state',undefined,admin)).json.news.filter(n=>n.sourceVillage==='riverstone');
 const fake=generated.find(n=>!n.authentic),real=generated.find(n=>n.authentic);
 assert.equal((await request('action',{op:'chooseNews',id:fake.id},alice)).status,200);
 assert.equal((await request('action',{op:'chooseNews',id:real.id},alice)).status,200);
 assert.equal((await request('action',{op:'revealNews'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.newsRevealed,true);assert.equal(s.news.find(x=>x.id===fake.id).authentic,false);
 assert.equal((await request('action',{op:'next'},admin)).status,200);
 assert.equal((await request('action',{op:'publish',title:'Come visit Green Valley!',body:'We have forests, culture and a wonderful community festival for everybody.',assets:['festival','bmw']},alice)).status,200);
 assert.equal((await request('action',{op:'revealMedia'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.mediaRevealed,true);assert.equal(s.assets.find(x=>x.id==='bmw').allowed,false);
 assert.equal((await request('action',{op:'next'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.round,4);assert.equal(s.tasks.length,16);
 const task=s.tasks.find(x=>x.village_id==='green-valley');
 assert.equal((await request('action',{op:'claimTask',id:task.id},alice)).status,200);
 db.exec('UPDATE game SET last_sim_at=last_sim_at-30000 WHERE id=1');
 s=(await request('state',undefined,alice)).json;assert.ok(s.tasks.find(x=>x.id===task.id).progress>0);
 assert.equal((await request('action',{op:'triggerTicket'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.tasks.length,24);
 assert.equal((await request('action',{op:'next'},admin)).status,200);
 s=(await request('state',undefined,alice)).json;assert.equal(s.game.round,5);
 const again=(await request('state',undefined,admin)).json;assert.ok(again.outbox.some(m=>m.subject.includes('account notification')));
 await request('action',{op:'end'},admin);
 const finished=(await request('state',undefined,admin)).json;
 const wipe=await request('admin/reset-game',{confirm:'RESET FINISHED GAME',sessionId:finished.game.sessionId,password:adminPass},admin);assert.equal(wipe.status,200);
 const cleared=(await request('state')).json;assert.equal(cleared.game.round,0);assert.equal(cleared.slots.length,0);
 db.close();
});
